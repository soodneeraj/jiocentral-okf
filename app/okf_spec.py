"""OKF (Open Knowledge Format) frontmatter validator and bundle index writer."""

from __future__ import annotations

from datetime import date
from pathlib import Path
from typing import Any

import yaml

from app.logger import get_logger

logger = get_logger(__name__)

VALID_TYPES = frozenset(
    {"document", "table", "figure", "metric", "index", "playbook"}
)

RECOMMENDED_FIELDS = (
    "title",
    "source",
    "source_loc",
    "tags",
    "business_unit",
    "owner",
    "related",
    "created",
    "confidentiality",
    "version",
    "section",
    "excluded",
)


def validate_okf_file(path: Path | str) -> tuple[dict[str, Any], str]:
    """Validate an OKF concept Markdown file.

    Returns ``(meta, body)``. Raises ``ValueError`` on structural/type/body
    failures. Recommended fields are checked where present but never enforced.
    """
    path = Path(path)
    raw = path.read_text(encoding="utf-8")

    if not raw.startswith("---"):
        raise ValueError(f"{path}: file must start with '---' frontmatter delimiter")

    parts = raw.split("---")
    if len(parts) < 3:
        raise ValueError(
            f"{path}: expected frontmatter delimited by '---' on both sides "
            f"(got {len(parts)} parts)"
        )
    # Exactly 3 parts when split on --- for a well-formed file
    # (leading empty, frontmatter, body). Extra --- inside body would yield
    # more parts; rejoin body segments to stay resilient.
    if len(parts) == 3:
        frontmatter_raw, body = parts[1], parts[2]
    else:
        frontmatter_raw = parts[1]
        body = "---".join(parts[2:])

    try:
        meta = yaml.safe_load(frontmatter_raw)
    except yaml.YAMLError as exc:
        raise ValueError(f"{path}: invalid YAML frontmatter: {exc}") from exc

    if not isinstance(meta, dict):
        raise ValueError(f"{path}: frontmatter must be a YAML mapping/dict")

    if "type" not in meta:
        raise ValueError(f"{path}: required field 'type' is missing")

    ctype = meta["type"]
    if ctype not in VALID_TYPES:
        raise ValueError(
            f"{path}: invalid type '{ctype}'; must be one of {sorted(VALID_TYPES)}"
        )

    body_stripped = body.strip()
    if len(body_stripped) <= 20:
        raise ValueError(
            f"{path}: body must be >20 characters (got {len(body_stripped)})"
        )

    for field in RECOMMENDED_FIELDS:
        if field in meta and meta[field] is None:
            logger.debug("%s: recommended field '%s' is present but null", path, field)

    return meta, body_stripped


def create_index_file(root: Path | str) -> Path:
    """Write/overwrite ``_index.md`` as the bundle root with ``type: index``."""
    root = Path(root)
    root.mkdir(parents=True, exist_ok=True)
    index_path = root / "_index.md"

    concepts = sorted(root.glob("concepts/**/*.md"))
    concept_count = len(concepts)

    body = (
        f"# Open Knowledge Format Bundle Index\n\n"
        f"This corpus contains {concept_count} concept file(s) under "
        f"`concepts/`. Generated by the Open OKF Enterprise RAG pipeline.\n\n"
        f"Do not embed this index file — `index_okf()` skips `type: index`.\n"
    )

    meta = {
        "type": "index",
        "title": "OKF Bundle Index",
        "source": "system",
        "source_loc": "",
        "tags": ["index", "okf"],
        "business_unit": "general",
        "owner": "system",
        "related": [],
        "created": str(date.today()),
        "confidentiality": "internal",
        "version": "V1.0",
    }

    fm = yaml.safe_dump(meta, sort_keys=False, allow_unicode=True).strip()
    index_path.write_text(f"---\n{fm}\n---\n\n{body}", encoding="utf-8")
    logger.info("Wrote bundle index: %s (%d concepts)", index_path, concept_count)
    return index_path
